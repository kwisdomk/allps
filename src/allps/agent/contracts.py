"""Pydantic domain contracts for the ALLPS AI Intelligence Layer.

Defines the structured handover schema, synthesized findings, epistemic
boundaries, and abstention types as codified in docs/AI_CONTRACT.md.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any
import uuid

from pydantic import BaseModel, Field, model_validator

from allps.policies.label_policy import check_for_prohibited_labels


class HandoverStatus(str, Enum):
    """Execution status of the pedagogical transition synthesis."""

    COMPLETED = "completed"
    ABSTAINED = "abstained"


class SynthesizedFinding(BaseModel):
    """A single sourced pedagogical finding with explicit epistemic boundaries.

    Separates factual observations from non-causal co-occurring factors
    and constructive teacher inquiry questions.
    """

    observation: str = Field(
        ...,
        min_length=1,
        description="Factual description of the observed pattern or status without causal assertions.",
    )
    supporting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="List of valid evidence_ids directly proving this observation.",
    )
    conflicting_evidence_ids: list[str] = Field(
        default_factory=list,
        description="Evidence records qualifying or contradicting this observation.",
    )
    co_occurring_factors: list[str] = Field(
        default_factory=list,
        description="Correlated phenomena (e.g. attendance dips) observed alongside the pattern without causal claims.",
    )
    teacher_inquiries: list[str] = Field(
        default_factory=list,
        description="Constructive questions for the educator to investigate in class.",
    )

    model_config = {"frozen": True}

    @model_validator(mode="after")
    def validate_no_prohibited_labels(self) -> "SynthesizedFinding":
        """Screen observation, co-occurring factors, and inquiries for deficit labels."""
        texts_to_check = [self.observation] + self.co_occurring_factors + self.teacher_inquiries
        for text in texts_to_check:
            bad = check_for_prohibited_labels(text)
            if bad:
                raise ValueError(
                    f"Prohibited deficit or diagnostic label detected in finding: {bad}"
                )
        return self


class CandidateHandoverBrief(BaseModel):
    """Candidate transition handover brief generated by the AI agent.

    Must go through human educator adjudication via ReviewItem before entering
    the surfaced learner profile.
    """

    brief_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    learner_id: str = Field(..., min_length=1)
    status: HandoverStatus
    summary: str = Field(
        ...,
        min_length=1,
        description="Pedagogical synthesis summarizing verifiable longitudinal trends.",
    )
    findings: list[SynthesizedFinding] = Field(default_factory=list)
    contradictions: list[str] = Field(
        default_factory=list,
        description="Documented contradictions between sources or evidence types.",
    )
    limitations: list[str] = Field(
        default_factory=list,
        description="Explicit caveats (e.g. missing terms, uncalibrated forms, small sample sizes).",
    )
    abstention_reason: str | None = Field(
        default=None,
        description="Required explanation if status is 'abstained'.",
    )
    generated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    model_config = {"frozen": True}

    @model_validator(mode="after")
    def validate_contract_invariants(self) -> "CandidateHandoverBrief":
        """Enforce strict contract rules for abstention and prohibited terminology."""
        # 1. Label policy screening across all narrative fields
        bad_summary = check_for_prohibited_labels(self.summary)
        if bad_summary:
            raise ValueError(
                f"Prohibited deficit or diagnostic label in handover summary: {bad_summary}"
            )

        for contradiction in self.contradictions:
            bad = check_for_prohibited_labels(contradiction)
            if bad:
                raise ValueError(
                    f"Prohibited deficit or diagnostic label in contradiction: {bad}"
                )

        # 2. Abstention invariants
        if self.status == HandoverStatus.ABSTAINED:
            if not self.abstention_reason or not self.abstention_reason.strip():
                raise ValueError(
                    "Handover with status 'abstained' must provide a non-empty abstention_reason."
                )
        elif self.status == HandoverStatus.COMPLETED:
            if not self.findings:
                raise ValueError(
                    "Handover with status 'completed' must include at least one SynthesizedFinding."
                )

        return self
